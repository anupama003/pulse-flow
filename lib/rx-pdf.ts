import "server-only";
import { PDFDocument, rgb, StandardFonts, type PDFFont, type PDFPage } from "pdf-lib";
import type { getPrescription } from "./opd/prescriptions";
import { istTime } from "./time";

type Rx = NonNullable<Awaited<ReturnType<typeof getPrescription>>>;

// A4 prescription PDF. Standard fonts only support WinAnsi, so text is sanitised.
const winAnsi = (s: string) => s.replace(/[“”]/g, '"').replace(/[‘’]/g, "'").replace(/[–—]/g, "-").replace(/₹/g, "Rs.").replace(/[^\x20-\x7E\xA0-\xFF]/g, "");

const INK = rgb(0.12, 0.11, 0.17);
const MUTED = rgb(0.45, 0.47, 0.55);
const LAVENDER = rgb(0.91, 0.9, 0.99);

export async function renderRxPdf(rx: Rx): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  pdf.setTitle(`Prescription ${rx.id}`);
  pdf.setAuthor(rx.consultant.name);
  pdf.setProducer("Pulse Flow");
  const page = pdf.addPage([595.28, 841.89]);
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const W = page.getWidth();
  let y = 800;

  const text = (s: string, x: number, size = 10, f: PDFFont = font, color = INK) => page.drawText(winAnsi(s), { x, y, size, font: f, color });
  const wrap = (s: string, x: number, width: number, size = 10, f: PDFFont = font, color = INK) => {
    const words = winAnsi(s).split(/\s+/);
    let line = "";
    for (const w of words) {
      const test = line ? `${line} ${w}` : w;
      if (f.widthOfTextAtSize(test, size) > width && line) {
        page.drawText(line, { x, y, size, font: f, color });
        y -= size + 4;
        line = w;
      } else line = test;
    }
    if (line) {
      page.drawText(line, { x, y, size, font: f, color });
      y -= size + 4;
    }
  };

  // Header
  page.drawRectangle({ x: 0, y: 760, width: W, height: 82, color: LAVENDER });
  text(rx.facility.name, 40, 18, bold);
  y -= 18;
  text(`${rx.facility.city}${rx.facility.phone ? ` · ${rx.facility.phone}` : ""}${rx.facility.hfrId ? ` · HFR ${rx.facility.hfrId}` : ""}`, 40, 9, font, MUTED);
  y = 800;
  text(rx.consultant.name, W - 220, 12, bold);
  y -= 15;
  text(`${rx.consultant.title ?? rx.consultant.department?.name ?? ""}`.slice(0, 40), W - 220, 9, font, MUTED);
  y -= 12;
  text(`HPR ID: ${rx.hprId ?? "-"}`, W - 220, 9, font, MUTED);

  // Patient
  y = 730;
  const p = rx.patient;
  text(`${p.name}  ·  ${p.age}y ${p.gender.charAt(0)}`, 40, 12, bold);
  text(`Date: ${(rx.signedAt ?? rx.createdAt).toLocaleDateString("en-IN", { timeZone: "Asia/Kolkata" })} ${istTime(rx.signedAt ?? rx.createdAt)}`, W - 220, 9, font, MUTED);
  y -= 15;
  text(
    [rx.appointment ? `Token ${rx.appointment.tokenLabel}` : null, p.abhaNumber ? `ABHA ${p.abhaNumber}` : null, p.allergies.length ? `Allergies: ${p.allergies.join(", ")}` : "No known allergies"]
      .filter(Boolean)
      .join("   ·   "),
    40, 9, font, MUTED,
  );
  if (rx.appointment?.symptomSummary) {
    y -= 14;
    text(`Complaint: ${rx.appointment.symptomSummary}`, 40, 9, font, MUTED);
  }

  // Rx
  y -= 30;
  text("Rx", 40, 22, bold);
  y -= 26;
  rx.items.forEach((it, i) => {
    const title = [it.form, it.drug, it.strength].filter(Boolean).join(" ");
    text(`${i + 1}.  ${title}`, 48, 11, bold);
    y -= 14;
    const sig = [it.dose, it.frequency, it.duration ? `x ${it.duration}` : null, it.route && it.route !== "ORAL" ? it.route : null].filter(Boolean).join("   ");
    wrap([sig, it.instructions, it.quantity ? `Qty: ${it.quantity}` : null].filter(Boolean).join("   ·   "), 64, W - 120, 10, font, MUTED);
    y -= 6;
  });

  const section = (title: string, lines: string[]) => {
    if (!lines.length) return;
    y -= 8;
    text(title, 40, 11, bold);
    y -= 15;
    for (const l of lines) wrap(`•  ${l}`, 48, W - 100, 10);
  };
  section("Investigations", rx.labOrders.map((l) => `${l.test}${l.urgency === "URGENT" ? " (urgent)" : ""}`));
  section("Advice", rx.advice);
  section("Follow-up", rx.followUp ? [rx.followUp] : []);

  // Signature block
  drawFooter(page, font, bold, rx);
  return pdf.save();
}

function drawFooter(page: PDFPage, font: PDFFont, bold: PDFFont, rx: Rx) {
  const W = page.getWidth();
  page.drawLine({ start: { x: 40, y: 110 }, end: { x: W - 40, y: 110 }, thickness: 0.5, color: MUTED });
  page.drawText(winAnsi(rx.status === "SIGNED" ? `Digitally signed by ${rx.consultant.name} (HPR ${rx.hprId})` : "DRAFT - NOT VALID FOR DISPENSING"), {
    x: 40, y: 92, size: 10, font: bold, color: INK,
  });
  if (rx.signatureHash) page.drawText(`SHA-256: ${rx.signatureHash}`, { x: 40, y: 78, size: 7, font, color: MUTED });
  page.drawText(winAnsi("Generated by Pulse Flow. Verify authenticity with the issuing facility. In an emergency call 108."), { x: 40, y: 60, size: 8, font, color: MUTED });
}
